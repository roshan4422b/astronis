export function getAdditionalServiceDetailPage(categorySlug: string, slug: string) {
  const config = configs.find((item) =>
    item.categorySlug === categorySlug
    && (item.slug === slug || serviceAnchor(item.title) === slug),
  );
  return config ? toPageData(config) : undefined;
}

