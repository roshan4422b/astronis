export function getServiceChildPageData(slug: string): EntityFormationPageData {
  const config = configs.find((page) => page.slug === slug);
  if (!config) throw new Error(`Unknown service child page: ${slug}`);
  return createPageData(config);
}

export function getServiceChildPageMetadata(slug: string): Metadata {
  const config = configs.find((page) => page.slug === slug);
  if (!config) throw new Error(`Unknown service child page: ${slug}`);
  return {
    title: `${config.title} | Astronis Global`,
    description: config.description,
    alternates: { canonical: config.route },
  };
}
