export function getRequestedServicePageMetadata(route: string): Metadata | undefined {
  const page = pages.find((item) => item.route === route || item.routeAliases?.includes(route));
  if (!page) return undefined;
  return {
    title: `${page.title} | ${page.serviceTitle} | Astronis`,
    description: page.description,
    alternates: { canonical: page.route },
    openGraph: {
      title: `${page.title} | ${page.serviceTitle} | Astronis`,
      description: page.description,
      url: page.route,
      type: "website",
    },
  };
}

